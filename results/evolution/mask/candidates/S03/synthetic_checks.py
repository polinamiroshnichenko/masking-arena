def run():
    bad = 0
    for text, want in CASES:
        res = solve.mask(text)
        got = [(r["placeholder"][1:].rsplit("_", 1)[0], r["original"]) for r in res["replacements"]]
        if not any(w[0] == "ФИО" for w in want):
            got = [g for g in got if g[0] != "ФИО"]  # старые кейсы структурных классов не проверяют ФИО
        # round-trip
        masked = res["masked_text"]
        for r in res["replacements"]:
            masked = masked.replace(r["placeholder"], r["original"], 1)
        assert masked == text, (text, res)
        if sorted(got) != sorted(want):
            bad += 1
            print("FAIL", json.dumps(text, ensure_ascii=False), "\n  want", want, "\n  got ", got)
    print("failed:", bad, "of", len(CASES))
    return bad


